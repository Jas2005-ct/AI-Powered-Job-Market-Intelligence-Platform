"""Page 4: AI-generated market narrative and beginner learning recommendations."""
from __future__ import annotations

import sys
from pathlib import Path

import streamlit as st

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from dashboard.data_loader import load_all  # noqa: E402
from src.ai.insights import build_context, market_summary, next_skills  # noqa: E402
from config import settings  # noqa: E402

st.set_page_config(page_title="AI Recommendations", page_icon="🤖", layout="wide")
st.title("🤖 AI Recommendations")

if not settings.GEMINI_API_KEY:
    st.caption("Gemini API key not configured — insights use the built-in rule-based engine.")
else:
    st.caption("Gemini API configured — insights are generated live.")

data = load_all()
context = build_context(data)

st.subheader("Market Narrative")
summary, source = market_summary(context)
st.markdown(summary)
st.caption(f"Generated by: {source}")

st.divider()
st.subheader("What Should a Beginner Learn Next?")

skills = data["top_skills"]
all_skills = skills["skill"].tolist() if not skills.empty else []
current = st.multiselect("Skills you already have", options=all_skills, default=[])
recommendations, rec_source = next_skills(current, context)

if recommendations:
    st.markdown("**Recommended next skills:**")
    if rec_source == "gemini":
        st.markdown(recommendations[0]["text"])
    else:
        for i, rec in enumerate(recommendations, 1):
            st.markdown(
                f"{i}. **{rec['skill']}** — {rec['demand_pct']:.0f}% of jobs request it "
                f"(priority score {rec['score']:.0f})."
            )
    st.caption(f"Generated by: {rec_source}")

st.divider()
st.subheader("Skill Combinations With the Best Coverage")
combos = data["skill_combinations"]
if combos is not None and not combos.empty:
    for row in combos.head(6).itertuples():
        st.markdown(f"- **{row.skill_a} + {row.skill_b}** — {row.times_together} postings")
